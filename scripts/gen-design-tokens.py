#!/usr/bin/env python3
"""Writes Milo's design tokens from protocol/design.json to where each platform reads them.

    uv run scripts/gen-design-tokens.py           # write both files
    uv run scripts/gen-design-tokens.py --check   # exit 1 if either is stale (the tests run this)

- app/Sources/MiloKit/Views/DesignTokens.swift: the Mac's constants, read by Theme.swift and Palette.swift.
- brain/src/milo/desktop/qml/Milo/design.json: the copy a frozen Windows/Linux build carries.

No dependencies: plain Python 3.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "protocol" / "design.json"
SWIFT = ROOT / "app" / "Sources" / "MiloKit" / "Views" / "DesignTokens.swift"
PACKAGED = ROOT / "brain" / "src" / "milo" / "desktop" / "qml" / "Milo" / "design.json"


def rgba(hex_colour: str) -> tuple[float, float, float, float]:
    """#RRGGBB or #AARRGGBB (Qt's order) as 0..1 components."""
    digits = hex_colour.lstrip("#")
    if len(digits) == 6:
        digits = "FF" + digits
    if len(digits) != 8:
        raise ValueError(f"not a colour: {hex_colour}")
    a, r, g, b = (int(digits[i:i + 2], 16) / 255 for i in range(0, 8, 2))
    return r, g, b, a


def _n(value: float) -> str:
    return f"{value:.4f}".rstrip("0").rstrip(".") if value not in (0, 1) else str(int(value))


def _ns(hex_colour: str) -> str:
    r, g, b, a = rgba(hex_colour)
    return f"NSColor(srgbRed: {_n(r)}, green: {_n(g)}, blue: {_n(b)}, alpha: {_n(a)})"


def _color(hex_colour: str) -> str:
    r, g, b, a = rgba(hex_colour)
    alpha = "" if a == 1 else f", opacity: {_n(a)}"
    return f"Color(.sRGB, red: {_n(r)}, green: {_n(g)}, blue: {_n(b)}{alpha})"


def swift(tokens: dict) -> str:
    motion = tokens["motion"]
    lines = [
        "// Generated by scripts/gen-design-tokens.py from protocol/design.json. Don't edit: change the JSON and",
        "// run the script.",
        "",
        "import AppKit",
        "import SwiftUI",
        "",
        "/// Milo's look and motion, shared with the Windows and Linux app.",
        "enum DesignTokens {",
        "    // Theme colours as (light, dark).",
    ]
    for name, (light, dark) in tokens["colors"].items():
        lines.append(f"    static var {name}: (NSColor, NSColor) {{ ({_ns(light)}, {_ns(dark)}) }}")
    lines += ["", "    // The wren's own colours and the voice modes, the same in light and dark."]
    for group in ("wren", "modes"):
        for name, value in tokens[group].items():
            lines.append(f"    static let {name} = {_color(value)}")
    lines += ["", "    /// Speakers in a meeting transcript, in turn: warm colours that read on Milo's paper.",
              "    static let speakers: [Color] = ["]
    lines += [f"        {_color(value)}," for value in tokens["speakers"]]
    lines += ["    ]", "", "    /// The wren as the rig draws him (WrenRig.swift), as 0xRRGGBB.", "    enum Rig {"]
    for name, value in tokens["rig"].items():
        if not name.startswith("$"):
            lines.append(f"        static let {name}: UInt32 = 0x{value.lstrip('#').upper()}")
    lines += ["    }", "", "    // Springs: response in seconds, damping fraction."]
    for kind in ("spring", "gentle", "snappy"):
        lines.append(f"    static let {kind}Response: Double = {motion[kind]['response']}")
        lines.append(f"    static let {kind}Damping: Double = {motion[kind]['damping']}")
    lines.append(f"    static let reducedFade: Double = {motion['reducedFade']}")
    lines.append(f"    static let bob: Double = {motion['bob']}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def outputs() -> dict[Path, str]:
    text = SOURCE.read_text(encoding="utf-8")
    return {SWIFT: swift(json.loads(text)), PACKAGED: text}


def main(argv: list[str]) -> int:
    stale = [path for path, text in outputs().items()
             if not path.is_file() or path.read_text(encoding="utf-8") != text]
    if "--check" in argv:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)} (run scripts/gen-design-tokens.py)")
        return 1 if stale else 0
    for path in stale:
        path.write_text(outputs()[path], encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
